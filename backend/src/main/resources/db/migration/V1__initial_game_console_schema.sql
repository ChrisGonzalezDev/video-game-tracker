CREATE TABLE consoles
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    CONSTRAINT consoles_name_not_blank CHECK (BTRIM(name) <> '')
);

CREATE TABLE games
(
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                           TEXT NOT NULL,
    original_release_year           SMALLINT NOT NULL,
    esrb_rating                     TEXT,
    max_local_multiplayer_players   INTEGER,
    cover_image_url                 TEXT,
    personal_comments               TEXT,
    CONSTRAINT games_title_not_blank CHECK (BTRIM(title) <> ''),
    CONSTRAINT games_release_year_valid CHECK (original_release_year >= 1000),
    CONSTRAINT games_esrb_rating_valid
        CHECK (esrb_rating IS NULL OR esrb_rating IN ('EC', 'E', 'E10+', 'T', 'M', 'AO', 'RP')),
    CONSTRAINT games_max_local_players_positive
        CHECK (max_local_multiplayer_players IS NULL OR max_local_multiplayer_players > 0)
);

CREATE TABLE game_consoles
(
    game_id    BIGINT NOT NULL REFERENCES games (id) ON DELETE CASCADE,
    console_id BIGINT NOT NULL REFERENCES consoles (id) ON DELETE RESTRICT,
    PRIMARY KEY (game_id, console_id)
);

CREATE FUNCTION enforce_game_has_console() RETURNS TRIGGER
    LANGUAGE plpgsql
AS
$$
DECLARE
    affected_game_id BIGINT;
    affected_game_ids BIGINT[];
BEGIN
    IF TG_TABLE_NAME = 'games' THEN
        affected_game_ids := ARRAY [NEW.id];
    ELSIF TG_OP = 'DELETE' THEN
        affected_game_ids := ARRAY [OLD.game_id];
    ELSIF TG_OP = 'UPDATE' THEN
        affected_game_ids := ARRAY [OLD.game_id, NEW.game_id];
    ELSE
        affected_game_ids := ARRAY [NEW.game_id];
    END IF;

    FOREACH affected_game_id IN ARRAY affected_game_ids
        LOOP
            IF EXISTS (SELECT 1 FROM games WHERE id = affected_game_id)
                AND NOT EXISTS (SELECT 1 FROM game_consoles WHERE game_id = affected_game_id) THEN
                RAISE EXCEPTION 'Game % must be associated with at least one console', affected_game_id
                    USING ERRCODE = '23514', CONSTRAINT = 'game_must_have_console';
            END IF;
        END LOOP;

    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER games_require_console
    AFTER INSERT OR UPDATE
    ON games
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
EXECUTE FUNCTION enforce_game_has_console();

CREATE CONSTRAINT TRIGGER game_consoles_require_console
    AFTER INSERT OR UPDATE OR DELETE
    ON game_consoles
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
EXECUTE FUNCTION enforce_game_has_console();
